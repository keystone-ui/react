#!/usr/bin/env node

/**
 * Generates the docs demo registry from the files under apps/docs/demos.
 *
 * Outputs (all generated, never hand-edited):
 *   apps/docs/demos/manifest.json  key → source file; the server-safe source
 *                                   of truth read by lib code, scripts and MCP
 *   apps/docs/demos/loader.tsx     "use client" map of next/dynamic imports;
 *                                   the only module that references demo
 *                                   components, so each demo is its own chunk
 *
 * Usage:
 *   node scripts/gen-demos.mjs          regenerate
 *   node scripts/gen-demos.mjs --check  exit 1 if any output is stale
 *
 * The naming rule lives in scripts/lib/demo-entries.mjs.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { demoEntriesFromPaths } from "./lib/demo-entries.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DEMOS_DIR = join(ROOT, "apps/docs/demos");
const HEADER =
  "// Generated by scripts/gen-demos.mjs from the files under apps/docs/demos.\n// Do not edit: run `pnpm gen:demos` (also wired into `pnpm lint:docs --check`).\n";

function walk(dir) {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) =>
      relative(DEMOS_DIR, join(entry.parentPath, entry.name))
        .split("\\")
        .join("/")
    );
}

function withoutExtension(file) {
  return file.replace(/\.tsx$/, "");
}

function renderManifest(entries) {
  const manifest = Object.fromEntries(entries.map((e) => [e.key, e.file]));
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function renderLoader(entries) {
  const lines = entries.map(
    (e) =>
      `  "${e.key}": dynamic(() =>
    import("./${withoutExtension(e.file)}").then((m) => ({
      default: hydrated("${e.key}", m.default),
    }))
  ),`
  );
  return `"use client";

${HEADER}
import dynamic from "next/dynamic";
import { type ComponentType, useEffect } from "react";

/**
 * Wraps a demo so the document records when it has hydrated. The wrapper
 * lives in the demo's own chunk, so its effect runs only after that chunk
 * has loaded and React has attached the demo's handlers; a click before
 * that moment is not reliably replayed. e2e/preview.ts waits for
 * \`html[data-demo-hydrated="<name>"]\` before interacting with a preview.
 */
function hydrated<P extends object>(
  name: string,
  Component: ComponentType<P>
): ComponentType<P> {
  function Hydrated(props: P) {
    useEffect(() => {
      document.documentElement.setAttribute("data-demo-hydrated", name);
    }, []);
    return <Component {...props} />;
  }
  Hydrated.displayName = \`Hydrated(\${name})\`;
  return Hydrated;
}

/**
 * One next/dynamic entry per demo. Because this is the only module that
 * references demo components, and it is a Client Component, Turbopack emits
 * a separate chunk per demo instead of one chunk holding all of them.
 */
const loaders: Record<string, ComponentType> = {
${lines.join("\n")}
};

export function hasDemo(name: string): boolean {
  return Object.hasOwn(loaders, name);
}

export function DemoLoader({ name }: { name: string }) {
  const Demo = Object.hasOwn(loaders, name) ? loaders[name] : undefined;
  return Demo ? <Demo /> : null;
}
`;
}

function main() {
  const check = process.argv.includes("--check");
  const entries = demoEntriesFromPaths(walk(DEMOS_DIR));
  const outputs = {
    "manifest.json": renderManifest(entries),
    "loader.tsx": renderLoader(entries),
  };

  const stale = [];
  for (const [name, content] of Object.entries(outputs)) {
    const path = join(DEMOS_DIR, name);
    let current = null;
    try {
      current = readFileSync(path, "utf-8");
    } catch {
      current = null;
    }
    if (current === content) {
      continue;
    }
    if (check) {
      stale.push(`apps/docs/demos/${name}`);
    } else {
      writeFileSync(path, content);
      console.log(`wrote apps/docs/demos/${name}`);
    }
  }

  if (check && stale.length > 0) {
    console.error(
      `Demo registry out of date (${stale.join(", ")}). Run \`pnpm gen:demos\`.`
    );
    process.exit(1);
  }
  console.log(
    `${check ? "OK —" : "Generated"} ${entries.length} demos${check ? " registered and up to date." : "."}`
  );
}

main();
