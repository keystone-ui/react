def full(s, n):
    rows=[r for r in s.strip('\n').split('\n')]
    out=[]
    for r in rows:
        h=r[:n//2].ljust(n//2,'.')
        out.append(h+h[::-1])
    assert len(out)==n, len(out)
    return out
def shade(g):
    n=len(g); o=[list(r) for r in g]
    at=lambda x,y: g[y][x] if 0<=x<n and 0<=y<n else '.'
    for y in range(n):
        for x in range(n):
            c=g[y][x]
            if c=='K':
                if at(x,y-1)!='K' or at(x-1,y)!='K': o[y][x]='H'
                elif at(x+1,y)!='K' or at(x,y+1)!='K': o[y][x]='S'
    return [''.join(r) for r in o]
