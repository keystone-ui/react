import { NextResponse } from "next/server";

import { resolveThemeVars } from "@/app/(home)/theme-builder/utils/generate-css-output";
import {
  decodeThemeCode,
  type ThemeSettings,
} from "@/app/(home)/theme-builder/utils/theme-code";

const JSON_SUFFIX = /\.json$/;
const LEADING_DASHES = /^--/;
const FONT_VARS = new Set(["font-sans"]);

/** `?only=theme` (colours + radius) or `?only=font`; omitted means both. */
type Part = "font" | "theme";

function parseOnly(value: string | null): Set<Part> {
  const parts = (value ?? "theme,font")
    .split(",")
    .filter((p): p is Part => p === "theme" || p === "font");
  return new Set(parts.length > 0 ? parts : ["theme", "font"]);
}

/** Drop the leading `--`: registry items name variables without it. */
function toRegistryVars(
  vars: Record<string, string>,
  keep: (name: string) => boolean
): Record<string, string> {
  return Object.fromEntries(
    Object.entries(vars)
      .map(
        ([name, value]) => [name.replace(LEADING_DASHES, ""), value] as const
      )
      .filter(([name]) => keep(name))
  );
}

export function buildThemeItem(
  code: string,
  settings: ThemeSettings,
  only: Set<Part>
) {
  const { darkVars, fontConfig, lightVars } = resolveThemeVars(settings);
  const keep = (name: string) =>
    FONT_VARS.has(name) ? only.has("font") : only.has("theme");
  return {
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: `theme-${code}`,
    type: "registry:theme",
    title: `Keystone theme (${settings.base}, ${fontConfig.label})`,
    description: `Generated by the keystone theme builder from code ${code}.`,
    cssVars: {
      light: toRegistryVars(lightVars, keep),
      dark: toRegistryVars(darkVars, keep),
    },
  };
}

/**
 * A theme-builder code served as a shadcn `registry:theme` item:
 *
 *   npx shadcn@latest add https://keystoneui.io/r/theme/<code>.json
 *
 * The code is the whole theme, so this computes rather than reads — no
 * filesystem, which the Worker does not have — and the response is
 * immutable: a code always describes the same theme.
 */
export async function GET(
  request: Request,
  { params }: { params: Promise<{ code: string }> }
) {
  const code = (await params).code.replace(JSON_SUFFIX, "");
  const settings = decodeThemeCode(code);

  if (!settings) {
    return NextResponse.json(
      { error: "Invalid theme code", code },
      { status: 404 }
    );
  }

  const only = parseOnly(new URL(request.url).searchParams.get("only"));

  return NextResponse.json(buildThemeItem(code, settings, only), {
    headers: { "Cache-Control": "public, max-age=31536000, immutable" },
  });
}
